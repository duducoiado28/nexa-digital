# Nexa Digital — Aplicativo Mobile

## Sobre o projeto

O Nexa Digital é um aplicativo mobile desenvolvido como atividade acadêmica da faculdade, utilizando React Native e Expo. O objetivo é praticar a criação de telas, navegação entre páginas, validação de login e organização do código em componentes e pastas.

## Funcionalidades

- **Login:** validação dos campos de usuário e senha.
- **Home:** tela inicial com apresentação da empresa e acesso às demais páginas.
- **Sobre:** informações sobre a empresa fictícia Nexa Digital, incluindo missão, visão e valores.
- **Contato:** informações de contato da empresa.
- **Navegação:** movimentação entre as telas do aplicativo.
- **Sair:** retorna à tela de login.
- **Estilização:** interface desenvolvida com StyleSheet do React Native.

## Tecnologias utilizadas

- React Native
- Expo Snack
- JavaScript
- StyleSheet

